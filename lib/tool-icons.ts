export type FormatKey = keyof typeof FORMATS;

export type OpKey =
  | "merge" | "split" | "compress" | "rotate" | "flip" | "pencil" | "pen"
  | "lock" | "key" | "shield" | "shieldX" | "drop" | "eraser" | "globe"
  | "clock" | "sparkle" | "bolt" | "wand" | "scissors" | "crop" | "ruler"
  | "search" | "eyeOff" | "check" | "plus" | "hash" | "tag" | "doc" | "book"
  | "mail" | "card" | "receipt" | "mic" | "music" | "volume" | "gauge"
  | "image" | "camera" | "palette" | "contrast" | "grid" | "diff" | "scan"
  | "link" | "phone" | "sliders" | "smile" | "qr" | "barcode" | "eq" | "quote";

export type ToolIconSpec =
  | { kind: "convert"; from: FormatKey; to: FormatKey }
  | { kind: "op"; badge: FormatKey; op: OpKey };

const c = (from: FormatKey, to: FormatKey): ToolIconSpec => ({ kind: "convert", from, to });
const o = (badge: FormatKey, op: OpKey): ToolIconSpec => ({ kind: "op", badge, op });

