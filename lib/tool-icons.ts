// File-type badge icon system (iLovePDF-style) — data side.
//
// Every tool renders as either:
//   • a CONVERSION icon: source format badge + target format badge + arrow
//     (e.g. PDF → W for "PDF to Word"), or
//   • an OPERATION icon: one format badge + a small action glyph bubble
//     (e.g. PDF + merge arrows for "Merge PDF").
//
// Specs are keyed by tool slug; unknown slugs fall back to a per-category
// default. Rendering lives in components/tools/ToolGlyph.tsx.

